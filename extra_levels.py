def generate_random_levels():
    map = [row[:] for row in template]

    portal_pos = random.randrange(len(map[0]))
    map[0][portal_pos] = 4

    for x in range(0, len(map)):
        for y in range(0, len(map[0])):
            if map[x][y] == 0:
                num = random.randint(1, 100)
                if num <= 80: # empty space
                    pass
                elif num >= 81 and num <= 95: # Platform
                    map[x][y] = 1
                elif num >= 96 and num <= 99: # Enemy
                    if x < len(map) - 2:
                        enemy_life = random.randint(1, 5)
                        if enemy_life >= 2: # One life enemy
                            map[x][y] = 2
                        else: # Two life enemy
                            map[x][y] = 5
                        map[x+1][y] = 1
                    else:
                        map[x][y] = 1
                elif num >= 100 and num <= 100:
                    map[x][y] = 3

    return map

